export function auditFor(row) {
  const id = row.ID
  let currentConclusion = '部分完成'
  let completion = 45
  let rationality = '合理，尚未闭环'

  if (candidateComplete.has(id) || ['CFG-02', 'UX-04', 'AUD-01'].includes(id)) {
    currentConclusion = '已完成（本地候选）'
    completion = 90
    rationality = '合理，本轮范围成立'
  } else if (baselinePass.has(id)) {
    currentConclusion = '已通过本地回归'
    completion = 80
    rationality = '合理，基线能力需保留'
  } else if (externallyBlocked.has(id)) {
    currentConclusion = '外部条件阻塞'
    completion = id === 'G-13' ? 15 : 40
    rationality = '合理，但依赖外部条件'
  } else if (futureVersion.has(id)) {
    currentConclusion = '未实现（后续版本）'
    completion = 20
    rationality = id.startsWith('A-') ? '合理，但必须收紧自动执行边界' : '合理，需独立版本'
  }

  if (['G-12', 'M-02', 'I-02', 'E-01', 'E-02', 'ADM-02', 'CFG-01', 'UX-02', 'UX-03'].includes(id)) completion = 65
  if (id === 'G-11') completion = 70
  if (['S-06', 'P-01', 'P-02', 'P-03', 'P-04', 'R-02', 'R-04', 'R-06', 'R-09', 'S-12', 'R-10', 'P-10', 'S-13', 'S-14', 'ADM-07'].includes(id)) completion = 45
  if (['S-07', 'M-03', 'M-04', 'I-03', 'E-03', 'E-04', 'ADM-03', 'ADM-04', 'ADM-05', 'A-03', 'A-04', 'A-05'].includes(id)) completion = 25

  const risk = riskOverrides[id] ?? defaultRisk(row, currentConclusion)
  const batch = recommendedBatch(row, currentConclusion)
  return {
    rationality,
    currentConclusion,
    completion,
    evidence: evidenceOverrides[id] ?? defaultEvidence(currentConclusion),
    configuration: configurationOverrides[id] ?? defaultConfiguration(row),
    risk,
    batch,
    estimate: estimateFor(row, currentConclusion),
  }
}

function defaultEvidence(status) {
  if (status === '已完成（本地候选）') return '代码、数据库和浏览器自动回归通过；尚未提交、部署或真实岗位验收。'
  if (status === '已通过本地回归') return '现有规范化能力已通过本地自动回归；尚未取得生产、真实岗位或外部渠道证据。'
  if (status === '外部条件阻塞') return '软件模拟或局部接口存在；缺少真实账号、渠道、硬件、网络或现场证据。'
  if (status === '未实现（后续版本）') return '仅有基础模型、摘要或历史能力，默认规范化入口尚未形成完整闭环。'
  return '现有接口或页面局部可用，但完成标准中的跨域状态、权限、配置或失败恢复仍有缺口。'
}

function defaultConfiguration(row) {
  const domain = row.领域
  if (['收银', '退款', '支付', '对账'].includes(domain)) return '按金额和岗位分权；资金动作人工确认、双人分离并保留审计。'
  if (domain === '预约') return '门店预约策略版本化；员工按岗位操作，顾客只能操作本人申请。'
  if (['商品', '库存', '配置', '主数据', '经营'].includes(domain)) return '经营参数可配置并版本化；普通员工只见本岗位必要入口。'
  if (['演出'].includes(domain)) return '演员、歌单、场次可配置；查看与发布权限分离。'
  if (['AI'].includes(domain)) return 'AI最小权限、只建议默认；写操作必须人工确认并读回。'
  if (['平台', '设备'].includes(domain)) return '部署/设备参数受控配置；普通员工不得修改安全边界。'
  if (['体验'].includes(domain)) return '随岗位、设备和门店配置自适应，不写死人员或桌台。'
  return '通过服务端岗位权限与门店配置控制，不向所有登录员工无差别开放。'
}

function defaultRisk(row, status) {
  if (status === '已完成（本地候选）') return '剩余风险为未提交、未部署和未做真实岗位/现场验收。'
  if (status === '已通过本地回归') return '自动回归不能替代真实岗位、设备和生产数据验证。'
  if (status === '外部条件阻塞') return '外部条件未到位，任何“可生产使用”结论都不成立。'
  if (String(row.优先级).includes('P0')) return '未闭环会造成交易、履约、权限或数据一致性风险，进入生产前必须关闭。'
  return '影响经营效率、配置准确性或失败恢复，应按独立版本关闭。'
}

function recommendedBatch(row, status) {
  if (status === '已完成（本地候选）') return 'V2.3当前候选'
  if (status === '已通过本地回归') return 'V2.3回归保留'
  if (status === '外部条件阻塞') return '外部渠道/设备联调'
  if (['收银', '退款', '支付', '对账', '出品', '配送'].includes(row.领域) || ['G-14', 'R-10', 'S-13', 'S-14'].includes(row.ID)) return 'V2.4交易与履约闭环'
  if (['预约', '商品', '库存', '配置', '主数据', '人员', '通知'].includes(row.领域)) return 'V2.5主数据与经营配置'
  return 'V2.6会员、经营与智能'
}

function estimateFor(row, status) {
  if (status === '已完成（本地候选）' || status === '已通过本地回归') return '审查后0.5–1人日收口提交；现场另计'
  if (status === '外部条件阻塞') return '资料/设备到位后2–5人日联调；另需3个营业晚班'
  if (status === '未实现（后续版本）') return String(row.优先级).includes('P0') ? '单项3–8人日，需合并排期' : '单项3–6人日，需合并排期'
  return String(row.优先级).includes('P0') ? '单项2–5人日，跨域项可能更长' : '单项2–4人日，需回归'
}
