import {readFile} from 'node:fs/promises'
import {expect,test} from '@playwright/test'

test('finds and partially settles an original closed invoice through real local HTTP, then retains settled history',async({page},testInfo)=>{
  const fixture=JSON.parse(await readFile(process.env.NORMALIZED_E2E_FIXTURE_FILE??'artifacts/normalized-browser/fixture.json','utf8'))
  test.skip(!fixture.crossDayDebtFixture,'Requires the isolated cross-day debt fixture')
  const debt=fixture.crossDayDebtFixture
  await page.setViewportSize({width:390,height:844})
  await page.goto(fixture.staffUrl)
  await page.getByLabel('门店口令').fill(fixture.dailyCredential)
  await page.getByRole('button',{name:/验证设备/}).click()
  await page.getByLabel('员工账号').fill('sanmu')
  await page.getByLabel('四位 PIN').fill(fixture.employeePin)
  await page.getByRole('button',{name:/进入工作台/}).click()
  await expect(page.getByTestId('normalized-workspace')).toBeVisible()
  const path=`/staff/payments?collectionScope=history&query=${debt.publicId}&orderId=${debt.orderId}`
  await page.goto(path)
  const card=page.locator(`[data-cashier-order-id="${debt.orderId}"]`)
  const collection=card.locator('.cashier-manual-collection')
  await expect(collection).toContainText('剩余应收 ¥120.00')
  await expect(collection).toContainText(`原营业日 ${debt.originalBusinessDate}`)
  const amount=card.getByLabel('本次收款金额（元，留空收取全部剩余欠款）')
  await card.getByRole('button',{name:'登记现金收款',exact:true}).click()
  await amount.fill('120.01')
  await expect(card.getByRole('button',{name:'核对并继续',exact:true})).toBeDisabled()
  await amount.fill('40')
  await card.getByRole('button',{name:'核对并继续',exact:true}).click()
  const first=page.waitForResponse(response=>response.request().method()==='POST'&&response.url().endsWith('/api/payments/manual'))
  await card.getByRole('button',{name:'确认已收到现金',exact:true}).click()
  const receipt=await first
  expect(receipt.status()).toBe(201)
  expect(receipt.request().postDataJSON()).toMatchObject({orderId:debt.orderId,amountMinor:4000,expectedOutstandingMinor:12000})
  await expect(collection).toContainText('剩余应收 ¥80.00')
  const dimensions=await page.evaluate(()=>({width:document.documentElement.clientWidth,content:Math.max(document.documentElement.scrollWidth,document.body.scrollWidth)}))
  expect(dimensions.content).toBeLessThanOrEqual(dimensions.width+1)
  await page.screenshot({path:testInfo.outputPath('cross-day-partial-mobile.png'),fullPage:true})
  await page.reload()
  await expect(collection).toContainText('剩余应收 ¥80.00')
  await amount.fill('')
  await card.getByRole('button',{name:'登记现金收款',exact:true}).click()
  await card.getByRole('button',{name:'核对并继续',exact:true}).click()
  const second=page.waitForResponse(response=>response.request().method()==='POST'&&response.url().endsWith('/api/payments/manual'))
  await card.getByRole('button',{name:'确认已收到现金',exact:true}).click()
  expect((await second).status()).toBe(201)
  await expect(collection).toHaveCount(0)
  const reread=page.waitForResponse(response=>response.url().includes('/api/payments/workbench?'))
  await page.reload()
  const view=(await (await reread).json()).data
  expect(view.orders.find((order:{id:string})=>order.id===debt.orderId)).toMatchObject({businessDate:debt.originalBusinessDate,tableSessionStatus:'closed',outstandingAmountMinor:0,paymentStatus:'paid'})
  await page.setViewportSize({width:1360,height:900})
  await expect(card).toBeVisible()
  await page.screenshot({path:testInfo.outputPath('cross-day-settled-desktop.png'),fullPage:true})
  await page.getByRole('button',{name:'未结账款',exact:true}).click()
  await expect(card).toHaveCount(0)
  await page.goto(path)
  await expect(card).toBeVisible()
  await page.getByLabel('起始营业日（留空不限）').fill(debt.originalBusinessDate)
  await page.getByLabel('结束营业日（留空不限）').fill(debt.originalBusinessDate)
  await expect(card).toBeVisible()
})
