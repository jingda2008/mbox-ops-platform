import {readFile} from 'node:fs/promises'
import {test,expect} from '@playwright/test'
test('会员报表：登录、筛选、消费明细、刷新和读取失败恢复',async({page},testInfo)=>{
 test.skip(process.env.NORMALIZED_E2E_MEMBER_REPORT!=='true','Requires isolated report fixture')
 const fixture=JSON.parse(await readFile('artifacts/normalized-browser/fixture.json','utf8'))
 await page.goto(fixture.staffUrl)
 await page.getByLabel('门店口令').fill(fixture.dailyCredential);await page.getByRole('button',{name:/验证设备/}).click()
 await page.getByLabel('员工账号').fill('chenfangyu');await page.getByLabel('四位 PIN').fill(fixture.employeePin);await page.getByRole('button',{name:/进入工作台/}).click()
 await expect(page.getByTestId('normalized-workspace')).toBeVisible()
 await page.goto('/staff/member-accounts')
 await page.getByRole('navigation',{name:'会员工作台'}).getByRole('button',{name:'会员报表',exact:true}).click()
 const panel=page.locator('.member-report')
 const reportRequests:string[]=[];page.on('request',r=>{if(r.url().includes('/api/staff/member-report'))reportRequests.push(r.url())})
 await expect(panel.getByRole('heading',{name:'会员查询报表',exact:true})).toBeVisible()
 await panel.getByLabel('会员号、姓名或完整手机号').fill('MBXREPORT88');await panel.getByRole('button',{name:'查询',exact:true}).click()
 await expect(panel).toContainText('符合条件 1 人');await expect(panel).toContainText('未填写')
 await panel.getByRole('button',{name:'查看消费'}).click();await expect(panel).toContainText('暂无已关联的成功收款记录');await expect(panel.getByRole('region',{name:'会员消费明细'}).getByRole('heading')).toBeInViewport()
 await panel.getByRole('button',{name:'关闭明细'}).click();await expect(panel.getByRole('button',{name:'查看消费'})).toBeFocused()
 await panel.getByLabel('有效兴趣卡').selectOption('yes');await panel.getByRole('button',{name:'查询',exact:true}).click();await expect(panel).toContainText('没有符合条件的会员')
 await page.route('**/api/staff/member-report',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:{code:'MEMBER_REPORT_UNAVAILABLE',message:'读取暂时失败'}})}))
 await panel.getByRole('button',{name:'重置'}).click();await expect(panel.getByRole('alert')).toContainText('读取失败')
 await page.unroute('**/api/staff/member-report');await panel.getByRole('button',{name:'重试',exact:true}).click();await expect(panel).toContainText('MBXREPORT88')
 await page.reload();await expect(page.locator('.member-report')).toContainText('MBXREPORT88')
 expect(reportRequests.length).toBeGreaterThan(0);expect(reportRequests.every(url=>!url.includes('?search=')&&!url.includes('MBXREPORT88'))).toBe(true)
 await page.screenshot({path:testInfo.outputPath('member-report-mobile.png'),fullPage:true})
})
