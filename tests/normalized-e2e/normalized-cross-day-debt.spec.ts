import {readFile} from 'node:fs/promises'
import {expect,test} from '@playwright/test'

for (const amount of ['680','0']) test(`reviews an unfulfilled cross-day staff tab as ${amount} through real local HTTP`,async({page},testInfo)=>{
  const fixture=JSON.parse(await readFile(process.env.NORMALIZED_E2E_FIXTURE_FILE??'artifacts/normalized-browser/fixture.json','utf8'))
  test.skip(!fixture.crossDayDebtFixture?.reviewOrderId,'Requires the isolated cross-day review fixture')
  const debt=fixture.crossDayDebtFixture,orderId=amount==='0'?debt.zeroReviewOrderId:debt.reviewOrderId
  await page.setViewportSize({width:390,height:844})
  await page.goto(fixture.staffUrl)
  await page.getByLabel('门店口令').fill(fixture.dailyCredential)
  await page.getByRole('button',{name:/验证设备/}).click()
  await page.getByLabel('员工账号').fill('sanmu')
  await page.getByLabel('四位 PIN').fill(fixture.employeePin)
  await page.getByRole('button',{name:/进入工作台/}).click()
  await expect(page.getByTestId('normalized-workspace')).toBeVisible()
  await page.goto(`/staff/payments?collectionScope=history&query=${amount==='0'?'DEBT-BROWSER-NO-DEBT':'DEBT-BROWSER-REVIEW'}&orderId=${orderId}`)
  const card=page.locator(`[data-cashier-order-id="${orderId}"]`)
  await page.getByRole('combobox',{name:'支付状态',exact:true}).selectOption('unpaid')
  await expect(card).toBeVisible()
  await card.getByRole('button',{name:'收款',exact:true}).click()
  await card.getByText('调整原单应收或记录无欠款（可选）',{exact:true}).click()
  const panel=card.locator('[aria-label="跨日挂账待核对"]')
  await expect(panel).toContainText('别出：隔离测试单')
  await expect(card.getByRole('button',{name:'出示付款二维码',exact:true})).toBeVisible()
  await expect(panel.getByRole('button',{name:'核对并继续',exact:true})).toBeDisabled()
  await panel.getByLabel('确认仍欠金额（元；无欠款填0）').fill('1314.01')
  await panel.getByLabel('核对依据').fill('隔离测试：核对原单与顾客约定及未收款事实')
  await expect(panel.getByRole('button',{name:'核对并继续',exact:true})).toBeDisabled()
  await panel.getByLabel('确认仍欠金额（元；无欠款填0）').fill(amount)
  await panel.getByRole('button',{name:'核对并继续',exact:true}).click()
  await expect(panel.getByRole('alert')).toBeVisible()
  await page.screenshot({path:testInfo.outputPath(`review-${amount}-before-confirm.png`),fullPage:true})
  const response=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith(`/orders/${orderId}/carryover-review`))
  await panel.getByRole('button',{name:'确认核对结果',exact:true}).click()
  const receipt=await response
  expect(receipt.status()).toBe(201)
  expect(receipt.request().postDataJSON()).toMatchObject({amountMinor:Number(amount)*100,confirmed:true,basis:{orderId,maximumAmountMinor:131400}})
  await page.getByRole('combobox',{name:'支付状态',exact:true}).selectOption('all')
  await expect(panel).toHaveCount(0)
  await page.reload()
  await expect(card).toContainText(amount==='0'?'挂账核对结果：无欠款':'挂账核对结果：确认欠款 ¥680.00')
  if (amount==='0') await expect(card.getByRole('button',{name:'登记现金收款',exact:true})).toHaveCount(0)
  else {
    await expect(card).toContainText('剩余应收 ¥680.00')
    await card.getByRole('button',{name:'登记现金收款',exact:true}).click()
    await card.getByRole('button',{name:'核对并继续',exact:true}).click()
    await card.getByRole('button',{name:'确认已收到现金',exact:true}).click()
    await expect(card).toContainText('已支付')
  }
  const dimensions=await page.evaluate(()=>({width:document.documentElement.clientWidth,content:Math.max(document.documentElement.scrollWidth,document.body.scrollWidth)}))
  expect(dimensions.content).toBeLessThanOrEqual(dimensions.width+1)
})

test('finds and partially settles an original closed invoice through real local HTTP, then retains settled history',async({page},testInfo)=>{
  const fixture=JSON.parse(await readFile(process.env.NORMALIZED_E2E_FIXTURE_FILE??'artifacts/normalized-browser/fixture.json','utf8'))
  test.skip(!fixture.crossDayDebtFixture,'Requires the isolated cross-day debt fixture')
  const debt=fixture.crossDayDebtFixture
  await page.setViewportSize({width:390,height:844})
  await page.goto(fixture.staffUrl)
  await page.getByLabel('门店口令').fill(fixture.dailyCredential)
  await page.getByRole('button',{name:/验证设备/}).click()
  await page.getByLabel('员工账号').fill('sanmu')
  await page.getByLabel('四位 PIN').fill(fixture.employeePin)
  await page.getByRole('button',{name:/进入工作台/}).click()
  await expect(page.getByTestId('normalized-workspace')).toBeVisible()
  const path=`/staff/payments?collectionScope=history&query=${debt.publicId}&orderId=${debt.orderId}`
  await page.goto(path)
  const card=page.locator(`[data-cashier-order-id="${debt.orderId}"]`)
  const collection=card.locator('.cashier-manual-collection')
  await expect(collection).toContainText('剩余应收 ¥120.00')
  await expect(collection).toContainText(`原营业日 ${debt.originalBusinessDate}`)
  const amount=card.getByLabel('本次收款金额（元，留空收取全部剩余欠款）')
  await card.getByRole('button',{name:'登记现金收款',exact:true}).click()
  await amount.fill('120.01')
  await expect(card.getByRole('button',{name:'核对并继续',exact:true})).toBeDisabled()
  await amount.fill('40')
  await card.getByRole('button',{name:'核对并继续',exact:true}).click()
  const first=page.waitForResponse(response=>response.request().method()==='POST'&&response.url().endsWith('/api/payments/manual'))
  await card.getByRole('button',{name:'确认已收到现金',exact:true}).click()
  const receipt=await first
  expect(receipt.status()).toBe(201)
  expect(receipt.request().postDataJSON()).toMatchObject({orderId:debt.orderId,amountMinor:4000,expectedOutstandingMinor:12000})
  await expect(collection).toContainText('剩余应收 ¥80.00')
  const dimensions=await page.evaluate(()=>({width:document.documentElement.clientWidth,content:Math.max(document.documentElement.scrollWidth,document.body.scrollWidth)}))
  expect(dimensions.content).toBeLessThanOrEqual(dimensions.width+1)
  await page.screenshot({path:testInfo.outputPath('cross-day-partial-mobile.png'),fullPage:true})
  await page.reload()
  await expect(collection).toContainText('剩余应收 ¥80.00')
  await amount.fill('')
  await card.getByRole('button',{name:'登记现金收款',exact:true}).click()
  await card.getByRole('button',{name:'核对并继续',exact:true}).click()
  const second=page.waitForResponse(response=>response.request().method()==='POST'&&response.url().endsWith('/api/payments/manual'))
  await card.getByRole('button',{name:'确认已收到现金',exact:true}).click()
  expect((await second).status()).toBe(201)
  await expect(collection).toHaveCount(0)
  const reread=page.waitForResponse(response=>response.url().includes('/api/payments/workbench?'))
  await page.reload()
  const view=(await (await reread).json()).data
  expect(view.orders.find((order:{id:string})=>order.id===debt.orderId)).toMatchObject({businessDate:debt.originalBusinessDate,tableSessionStatus:'closed',outstandingAmountMinor:0,paymentStatus:'paid'})
  await page.setViewportSize({width:1360,height:900})
  await expect(card).toBeVisible()
  await page.screenshot({path:testInfo.outputPath('cross-day-settled-desktop.png'),fullPage:true})
  await page.getByRole('button',{name:'未结账款',exact:true}).click()
  await expect(card).toHaveCount(0)
  await page.goto(path)
  await expect(card).toBeVisible()
  await page.getByLabel('起始营业日（留空不限）').fill(debt.originalBusinessDate)
  await page.getByLabel('结束营业日（留空不限）').fill(debt.originalBusinessDate)
  await expect(card).toBeVisible()
})

for(const status of ['pending','accepted','preparing'])test(`collects before production completes while ${status} through real local HTTP`,async({page})=>{
  const fixture=JSON.parse(await readFile(process.env.NORMALIZED_E2E_FIXTURE_FILE??'artifacts/normalized-browser/fixture.json','utf8'))
  test.skip(!fixture.crossDayDebtFixture?.activeOrders,'Requires isolated production collection fixture')
  const order=fixture.crossDayDebtFixture.activeOrders.find((row:{status:string})=>row.status===status)
  await page.setViewportSize({width:390,height:844})
  await page.goto(fixture.staffUrl)
  await page.getByLabel('门店口令').fill(fixture.dailyCredential)
  await page.getByRole('button',{name:/验证设备/}).click()
  await page.getByLabel('员工账号').fill('sanmu')
  await page.getByLabel('四位 PIN').fill(fixture.employeePin)
  await page.getByRole('button',{name:/进入工作台/}).click()
  await expect(page.getByTestId('normalized-workspace')).toBeVisible()
  const initial=page.waitForResponse(r=>r.url().includes('/api/payments/workbench?')&&r.url().includes(order.publicId))
  await page.goto(`/staff/payments?query=${order.publicId}`)
  const card=page.locator(`[data-cashier-order-id="${order.orderId}"]`)
  await card.getByRole('button',{name:'收款',exact:true}).click()
  const original=(await (await initial).json()).data.orders[0]
  expect(original.kdsTasks[0].status).toBe(status)
  await expect(card.getByRole('button',{name:'出示付款二维码',exact:true})).toBeVisible()
  await card.getByRole('button',{name:'登记现金收款',exact:true}).click()
  await card.getByRole('button',{name:'核对并继续',exact:true}).click()
  const updated=page.waitForResponse(r=>r.url().includes('/api/payments/workbench?')&&r.url().includes(order.publicId))
  await card.getByRole('button',{name:'确认已收到现金',exact:true}).click()
  await expect(card).toContainText('已支付')
  const paid=(await (await updated).json()).data.orders[0]
  expect(paid.paymentStatus).toBe('paid')
  expect(paid.kdsTasks).toEqual(original.kdsTasks)
  expect(paid.items).toEqual(original.items)
  expect(paid.payments.filter((p:{status:string})=>p.status==='succeeded')).toHaveLength(1)
})

