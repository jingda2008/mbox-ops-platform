import { readFile } from 'node:fs/promises'
import { test, expect } from '@playwright/test'

test('费用录入后可查询修改，单金额保存和历史记录在刷新后仍正确', async ({ page }) => {
  const fixture = JSON.parse(await readFile('artifacts/normalized-browser/fixture.json', 'utf8'))
  const employee = fixture.employees.find((item: {roleNames: string[]}) => item.roleNames.includes('财务'))
    ?? fixture.employees.find((item: {roleNames: string[]}) => item.roleNames.includes('老板'))
  await page.goto(fixture.staffUrl)
  await page.getByLabel('门店口令').fill(fixture.dailyCredential)
  await page.getByRole('button', { name: /验证设备/ }).click()
  await page.getByLabel('员工账号').fill(employee.code)
  await page.getByLabel('四位 PIN').fill(fixture.employeePin)
  await page.getByRole('button', { name: /进入工作台/ }).click()
  await expect(page.getByTestId('normalized-workspace')).toBeVisible()
  await page.goto('/staff/operations')
  const panel = page.getByRole('region', { name: '财务仪表盘', exact: true })
  await expect(panel.getByRole('region', { name: '费用汇总' })).toBeVisible()
  await panel.getByRole('button', { name: '录入费用', exact: true }).click()
  await panel.getByLabel('费用名称', { exact: true }).fill('浏览器财务租金')
  await panel.getByLabel('金额', { exact: true }).fill('106.35')
  await expect(panel.getByLabel('税额', { exact: true })).toHaveCount(0)
  // A past date outside the default range must remain visible after saving.
  await panel.getByLabel('费用开始', { exact: true }).fill('2026-01-01')
  await panel.getByLabel('费用结束', { exact: true }).fill('2026-01-31')
  await panel.getByLabel('收款方（选填）').fill('测试收款方')
  await panel.getByRole('button', { name: '记录费用', exact: true }).click()
  const row = panel.locator('.owner-finance-list article').filter({ hasText: '浏览器财务租金' })
  await expect(row).toContainText('¥106.35')
  await expect(panel.getByLabel('记录开始日期')).toHaveValue('2026-01-01')
  await row.getByText('查看详情', { exact: true }).click()
  await expect(row).toContainText('测试收款方')
  await row.getByRole('button', { name: '查看 / 修改' }).click()
  await expect(panel.getByLabel('金额', { exact: true })).toHaveValue('106.35')
  await panel.getByLabel('金额', { exact: true }).fill('128.90')
  await panel.getByLabel('更正原因', { exact: true }).fill('核对票据后修正金额')
  await panel.getByRole('button', { name: '保存更正', exact: true }).click()
  await expect(row).toHaveCount(1)
  await expect(row).toContainText('¥128.90')
  await expect(panel.getByRole('region', { name: '费用汇总' })).toContainText('¥128.90')
  await panel.getByLabel('显示已被更正的历史记录').check()
  await expect(row).toHaveCount(2)
  await expect(row.filter({ hasText: '历史记录' }).getByRole('button', { name: '查看 / 修改' })).toHaveCount(0)
  await page.reload()
  await panel.getByLabel('记录开始日期').fill('2026-01-01')
  await panel.getByLabel('记录结束日期').fill('2026-01-31')
  await expect(row).toHaveCount(1)
  await expect(row).toContainText('¥128.90')
  await panel.getByLabel('搜索费用').fill('测试收款方')
  await expect(row).toHaveCount(1)
  for (const width of [320, 390, 1280]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1)).toBe(true)
  }
  await page.screenshot({ path: 'artifacts/normalized-browser/finance-dashboard.png', fullPage: true })
  await panel.getByRole('button', { name: '周期费用', exact: true }).click()
  await panel.getByLabel('规则名称', { exact: true }).fill('浏览器周期费用')
  await panel.getByLabel('每期金额', { exact: true }).fill('88.88')
  await expect(panel.getByLabel('税额', { exact: true })).toHaveCount(0)
  await panel.getByRole('button', { name: '保存周期规则', exact: true }).click()
  const rule = panel.locator('.owner-finance-list article').filter({ hasText: '浏览器周期费用' })
  await expect(rule).toContainText('¥88.88/期')
  await rule.getByRole('button', { name: '修改规则', exact: true }).click()
  await expect(panel.getByLabel('每期金额', { exact: true })).toHaveValue('88.88')
  await panel.getByLabel('每期金额', { exact: true }).fill('99.99')
  await panel.getByLabel('修改原因', { exact: true }).fill('调整后续周期费用')
  await panel.getByRole('button', { name: '保存规则修改', exact: true }).click()
  await expect(rule).toContainText('¥99.99/期')
  await page.reload()
  await panel.getByRole('button', { name: '周期费用', exact: true }).click()
  await expect(rule).toContainText('¥99.99/期')
  await panel.getByRole('button', { name: '费用总览', exact: true }).click()

  // A failed refresh must not present a zero balance or stale data as fresh.
  await page.route('**/api/commercial-ops/owner-finance?*', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '测试读取失败' } } }))
  await panel.getByRole('button', { name: '刷新经营费用' }).click()
  await expect(panel).toContainText('读取失败，请刷新重试')
  await expect(panel.getByRole('region', { name: '费用汇总' })).toHaveCount(0)
})
