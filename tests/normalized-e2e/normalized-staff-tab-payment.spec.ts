import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

test('320px employee explicitly tabs an order and recovers the original after losing its receipt', async ({page}) => {
  const fixture = JSON.parse(await readFile(process.env.NORMALIZED_E2E_FIXTURE_FILE ?? 'artifacts/normalized-browser/fixture.json','utf8'))
  await page.setViewportSize({width:320,height:844})
  await page.goto(fixture.staffUrl)
  await page.getByLabel('门店口令').fill(fixture.dailyCredential)
  await page.getByRole('button',{name:/验证设备/}).click()
  await page.getByLabel('员工账号').fill('liyan')
  await page.getByLabel('四位 PIN').fill(fixture.employeePin)
  const signIn = page.getByRole('button',{name:/进入工作台/})
  await signIn.click()
  await expect(signIn).toBeHidden()
  await page.goto('/staff/live')
  await page.getByRole('button',{name:/^W0?1\s/}).click()
  const desk = page.getByRole('dialog',{name:/桌台操作/})
  await desk.getByRole('button',{name:'协助点单',exact:true}).click()
  const sheet = page.getByRole('dialog',{name:/W0?1.*协助点单/})
  await expect(sheet.getByRole('button',{name:'立即结算',exact:true})).toHaveAttribute('aria-pressed','true')
  await sheet.getByRole('button',{name:'挂桌账',exact:true}).click()
  await sheet.getByLabel('搜索菜单商品').fill(fixture.orderableProductName)
  await sheet.getByRole('button',{name:'加入'+fixture.orderableProductName,exact:true}).click()
  await sheet.getByRole('button',{name:'查看已选',exact:true}).click()
  await sheet.getByRole('dialog',{name:'购物车明细'}).getByRole('button',{name:'核对无误，确认下单'}).click()

  const attempts: {id:string;key:string;status:number}[] = []
  await page.route('**/api/commerce/orders',async route => {
    if (route.request().method() !== 'POST') return route.continue()
    const response = await route.fetch()
    const body = await response.json()
    attempts.push({id:body.id,key:route.request().headers()['idempotency-key'],status:response.status()})
    if (attempts.length === 1) await route.abort('failed')
    else await route.fulfill({response})
  })
  const submit = sheet.getByRole('dialog',{name:'确认上单'}).getByRole('button',{name:'确认上单',exact:true})
  await submit.click()
  await expect(sheet.getByText(/失败|重试|网络|fetch|连接/i).first()).toBeVisible()
  await submit.click()
  await expect(page.locator('.staff-actions-notice')).toContainText('已挂桌账，未收齐，已送制作')
  expect(attempts.map(a=>a.status)).toEqual([201,200])
  expect(attempts[0].id).toBeTruthy()
  expect(attempts[0].key).toBeTruthy()
  expect(attempts[1]).toMatchObject({id:attempts[0].id,key:attempts[0].key})
  await expect(desk.getByText('员工挂桌账，未收齐，可制作').first()).toBeVisible()
  await desk.getByRole('button',{name:'关闭桌台操作'}).click()
  const notice = page.locator('.order-production-notices')
  await expect(notice).toContainText('员工挂桌账',{timeout:40_000})
  const summary=notice.locator('summary')
  expect((await summary.boundingBox())?.height).toBeGreaterThanOrEqual(44)
  await summary.click()
  await expect(notice).toContainText('待收 ¥')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
})

test('收银台从原挂桌入口核对原单，未知单号不能发起扣分',async({page})=>{
  const fixture=JSON.parse(await readFile(process.env.NORMALIZED_E2E_FIXTURE_FILE??'artifacts/normalized-browser/fixture.json','utf8'))
  await page.setViewportSize({width:390,height:844})
  await page.goto(fixture.staffUrl)
  await page.getByLabel('门店口令').fill(fixture.dailyCredential)
  await page.getByRole('button',{name:/验证设备/}).click()
  await page.getByLabel('员工账号').fill('sanmu')
  await page.getByLabel('四位 PIN').fill(fixture.employeePin)
  await page.getByRole('button',{name:/进入工作台/}).click()
  await expect(page.getByTestId('normalized-workspace')).toBeVisible()
  await page.goto('/staff/payments')
  const panel=page.locator('details').filter({has:page.getByText('原挂桌单使用会员积分',{exact:true})})
  await panel.locator('summary').click()
  await panel.getByLabel('原挂桌单号').fill('LOCAL-MISSING-TAB')
  await panel.getByLabel('购餐会员号').fill('LOCAL-MISSING-MEMBER')
  const response=page.waitForResponse(r=>r.url().endsWith('/commerce/existing-tab-points'))
  await panel.getByRole('button',{name:'填入本单最多可用的积分'}).click()
  expect((await response).status()).toBe(409)
  await expect(panel.getByRole('status')).toContainText('请核对原挂桌订单号')
})
